-- Create table for GST HSN/SAC rates
CREATE TABLE IF NOT EXISTS public.gst_rates (
    id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    item_name text NOT NULL,
    gst_rate integer NOT NULL,
    code_type text,
    code text,
    notes text,
    created_at timestamp with time zone DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.gst_rates ENABLE ROW LEVEL SECURITY;

-- Allow public read access
CREATE POLICY "Public can view gst rates" ON public.gst_rates
    FOR SELECT USING (true);

-- Allow admin full access
CREATE POLICY "Admins can manage gst rates" ON public.gst_rates
    FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

